from pathlib import Path
import pandas as pd
from flask import Flask, render_template, send_from_directory, abort

# --- Robust path handling: resolve relative to project root ---
PROJECT_ROOT = Path(__file__).resolve().parent.parent
DASHBOARD_DIR = Path(__file__).resolve().parent
TEMPLATES_DIR = DASHBOARD_DIR / "templates"
STATIC_DIR = DASHBOARD_DIR / "static"
FIGURES_DIR = PROJECT_ROOT / "reports" / "figures"
SUBMISSION_CANDIDATES = [
    PROJECT_ROOT / "submission.csv",
    PROJECT_ROOT / "notebooks" / "submission.csv",
]
TEST_PATH = PROJECT_ROOT / "data" / "raw" / "test.csv"
TRAIN_PATH = PROJECT_ROOT / "data" / "raw" / "train.csv"

# Verified metrics from notebook (single source of truth) — do not change
RIDGE_WAPE = 0.1854
BASELINE_WAPE = 0.2177
IMPROVEMENT_PCT = 14.7
NAIVE_WAPE = 0.2330

app = Flask(__name__, template_folder=str(TEMPLATES_DIR), static_folder=str(STATIC_DIR))


def load_forecast():
    """Load forecast from submission.csv (root or notebooks fallback). Enrich with test.csv if available."""
    submission_path = None
    for cand in SUBMISSION_CANDIDATES:
        if cand.exists():
            submission_path = cand
            break
    if submission_path is None:
        return {
            "found": False,
            "submission_path": None,
            "df": None,
            "enriched": None,
            "summary": None,
            "error": f"No submission file found. Checked: {', '.join(str(p) for p in SUBMISSION_CANDIDATES)}",
        }
    try:
        df = pd.read_csv(submission_path)
        if "id" not in df.columns or "sales" not in df.columns:
            return {
                "found": False,
                "submission_path": str(submission_path),
                "df": None,
                "enriched": None,
                "summary": None,
                "error": f"submission.csv missing required columns. Found: {list(df.columns)}",
            }
        summary = {
            "rows": len(df),
            "sales_sum": float(df["sales"].sum()),
            "sales_mean": float(df["sales"].mean()),
            "sales_min": float(df["sales"].min()),
            "sales_max": float(df["sales"].max()),
            "missing": int(df["sales"].isna().sum()),
            "negative": int((df["sales"] < 0).sum()),
        }
        enriched = None
        horizon_days = None
        date_min = None
        date_max = None
        date_min_fmt = None
        date_max_fmt = None
        if TEST_PATH.exists():
            try:
                test_df = pd.read_csv(TEST_PATH)
                if "id" in test_df.columns:
                    enriched = test_df.merge(df, on="id", how="left", suffixes=("", "_pred"))
                    if "sales_pred" in enriched.columns:
                        enriched["sales"] = enriched["sales_pred"]
                    if "date" in enriched.columns:
                        try:
                            enriched["date"] = pd.to_datetime(enriched["date"])
                            horizon_days = enriched["date"].nunique()
                            dmin = enriched["date"].min()
                            dmax = enriched["date"].max()
                            date_min = str(dmin.date())
                            date_max = str(dmax.date())
                            date_min_fmt = dmin.strftime("%d %B %Y")
                            date_max_fmt = dmax.strftime("%d %B %Y")
                            # also keep short range like "16 August – 31 August 2017"
                            date_min_short = dmin.strftime("%d %B")
                            date_max_short = dmax.strftime("%d %B %Y" if dmin.year != dmax.year else "%d %B %Y")
                            summary["date_range_short"] = f"{date_min_short} \u2013 {date_max_short}"
                        except Exception:
                            pass
                    summary["horizon_days"] = horizon_days
                    summary["date_min"] = date_min
                    summary["date_max"] = date_max
                    summary["date_min_fmt"] = date_min_fmt
                    summary["date_max_fmt"] = date_max_fmt
            except Exception as e:
                summary["enrich_error"] = str(e)
        return {
            "found": True,
            "submission_path": str(submission_path.relative_to(PROJECT_ROOT)) if submission_path.is_relative_to(PROJECT_ROOT) else str(submission_path),
            "df": df,
            "enriched": enriched,
            "summary": summary,
            "error": None,
        }
    except Exception as e:
        return {
            "found": False,
            "submission_path": str(submission_path),
            "df": None,
            "enriched": None,
            "summary": None,
            "error": str(e),
        }


def get_figures():
    if not FIGURES_DIR.exists():
        return []
    try:
        exts = {".png", ".jpg", ".jpeg", ".svg", ".gif", ".webp"}
        files = [p for p in FIGURES_DIR.iterdir() if p.is_file() and p.suffix.lower() in exts]
        return sorted(files, key=lambda p: p.name)
    except Exception:
        return []


