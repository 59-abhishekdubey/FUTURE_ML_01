@app.route("/")
def index():
    forecast = load_forecast()
    figures = get_figures()
    top_families, top_stores, top_dates = get_error_analysis()

    # Derived display values (no new calculations beyond formatting)
    forecast_error_pct = f"{RIDGE_WAPE*100:.1f}%"
    simple_error_pct = f"{BASELINE_WAPE*100:.1f}%"
    improvement_pct = f"{IMPROVEMENT_PCT:.1f}%"

    # Expected sales total
    expected_sales_formatted = None
    expected_sales_short = None
    if forecast["found"] and forecast["summary"]:
        total = forecast["summary"]["sales_sum"]
        # Format as ₹13.02M
        expected_sales_formatted = f"\u20B9{total/1e6:.2f}M"
        expected_sales_short = f"{total:,.0f}"

    # Forecast period — actual test dates are 16 days (Aug 16-31 inclusive)
    # Use enriched summary if available, else fallback to hardcoded known range
    if forecast["found"] and forecast["summary"] and forecast["summary"].get("horizon_days"):
        horizon_days = forecast["summary"]["horizon_days"]
        date_range_short = forecast["summary"].get("date_range_short", "16 August \u2013 31 August 2017")
        date_min_fmt = forecast["summary"].get("date_min_fmt", "16 August 2017")
        date_max_fmt = forecast["summary"].get("date_max_fmt", "31 August 2017")
    else:
        horizon_days = 16
        date_range_short = "16 August \u2013 31 August 2017"
        date_min_fmt = "16 August 2017"
        date_max_fmt = "31 August 2017"

    # Prepare forecast table with friendly column names
    forecast_table = None
    forecast_columns = []
    friendly_columns = []
    table_total_rows = 0
    if forecast["found"] and forecast["df"] is not None:
        if forecast["enriched"] is not None:
            desired = ["date", "store_nbr", "family", "onpromotion", "sales"]
            available = [c for c in desired if c in forecast["enriched"].columns]
            forecast_table = forecast["enriched"][available].head(50)
            table_total_rows = len(forecast["enriched"])
            # Map to friendly names for display
            col_map = {
                "date": "Date",
                "store_nbr": "Store",
                "family": "Product category",
                "onpromotion": "Promotion items",
                "sales": "Expected sales",
            }
            friendly_columns = [col_map.get(c, c) for c in available]
            forecast_columns = available
        else:
            forecast_table = forecast["df"].head(50)
            table_total_rows = len(forecast["df"])
            forecast_columns = list(forecast["df"].columns)
            friendly_columns = ["ID" if c=="id" else "Expected sales" if c=="sales" else c for c in forecast_columns]

        if forecast_table is not None and "date" in forecast_table.columns:
            forecast_table = forecast_table.copy()
            forecast_table["date"] = pd.to_datetime(forecast_table["date"]).dt.strftime("%Y-%m-%d")
        # Format sales for display but keep numeric for template logic
        table_records = forecast_table.to_dict(orient="records") if forecast_table is not None else []
    else:
        table_records = []
        friendly_columns = []

    dataset_info = {}
    if TRAIN_PATH.exists():
        try:
            train_head = pd.read_csv(TRAIN_PATH, nrows=3)
            dataset_info["train_cols"] = list(train_head.columns)
        except Exception:
            dataset_info["train_cols"] = ["id", "date", "store_nbr", "family", "sales", "onpromotion"]
    else:
        dataset_info["train_cols"] = ["id", "date", "store_nbr", "family", "sales", "onpromotion"]

    figure_names = [f.name for f in figures]

    return render_template(
        "index.html",
        ridge_wape=RIDGE_WAPE,
        baseline_wape=BASELINE_WAPE,
        naive_wape=NAIVE_WAPE,
        improvement=IMPROVEMENT_PCT,
        forecast_error_pct=forecast_error_pct,
        simple_error_pct=simple_error_pct,
        improvement_pct=improvement_pct,
        expected_sales_formatted=expected_sales_formatted,
        expected_sales_short=expected_sales_short,
        horizon_days=horizon_days,
        date_range_short=date_range_short,
        date_min_fmt=date_min_fmt,
        date_max_fmt=date_max_fmt,
        forecast=forecast,
        figures=figure_names,
        figures_dir_exists=FIGURES_DIR.exists(),
        forecast_table=table_records,
        forecast_columns=forecast_columns,
        friendly_columns=friendly_columns,
        table_total_rows=table_total_rows,
        top_families=top_families,
        top_stores=top_stores,
        top_dates=top_dates,
        dataset_info=dataset_info,
    )


@app.route("/reports/figures/<path:filename>")
def serve_figure(filename):
    if not FIGURES_DIR.exists():
        abort(404)
    allowed = {".png", ".jpg", ".jpeg", ".svg", ".gif", ".webp"}
    if Path(filename).suffix.lower() not in allowed:
        abort(404)
    return send_from_directory(str(FIGURES_DIR), filename)


@app.route("/health")
def health():
    return {"status": "ok", "ridge_wape": RIDGE_WAPE, "baseline_wape": BASELINE_WAPE}


if __name__ == "__main__":
    app.run(host="127.0.0.1", port=5000, debug=False)
